// Builds worker.js — the public template without the Mr. Challenger persona — from
// worker-mr-challenger.js: the block between `// <texts>` and `// </texts>` is replaced by
// template/texts.js, everything else is the same code.
//
//   node scripts/build-template.mjs
//
// tests/texts-drift.test.mjs fails when worker.js is out of date.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const START = "// <texts>\n";
const END = "// </texts>\n";
const HEADER = "// Generated by scripts/build-template.mjs from worker-mr-challenger.js and template/texts.js — edit those.\n";

function blockBounds(source) {
  const start = source.indexOf(START);
  const end = source.indexOf(END);
  if (start < 0 || end < start) throw new Error("the `// <texts>` … `// </texts>` block was not found");
  return [start + START.length, end];
}

/** The code inside the texts block. */
export function textsBlock(source) {
  const [from, to] = blockBounds(source);
  return source.slice(from, to);
}

export function buildTemplate(botSource, neutralTexts) {
  const [from, to] = blockBounds(botSource);
  return HEADER + botSource.slice(0, from) + neutralTexts.trimEnd() + "\n" + botSource.slice(to);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const read = (name) => readFileSync(join(root, name), "utf8").replace(/\r\n/g, "\n");
  writeFileSync(join(root, "worker.js"), buildTemplate(read("worker-mr-challenger.js"), read("template/texts.js")));
  console.log("worker.js rebuilt");
}
